import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { FAMILIES, type Catalog, type CatalogCell, type Family } from './schema.js';

/**
 * The cell catalog, one file per family (fixtures/apps/cells/<family>.json, schema.ts#FAMILIES), and the one catalog
 * both lab apps bundle (fixtures/apps/cells.json) GENERATED from them: the families in FAMILIES's order, each cell
 * stamped with its `family` (the apps route a cell to their family's file by it). Families are written apart — phase 3's
 * batches each own one file — and the generated file is never edited by hand: tests/truth/catalog.test.ts fails while
 * the committed cells.json is not what the family files generate.
 *
 *   node --import tsx scripts/truth/catalog.ts           # rewrite fixtures/apps/cells.json
 *   node --import tsx scripts/truth/catalog.ts --check   # exit 1 when it is stale
 */

export const APPS = fileURLToPath(new URL('../../fixtures/apps/', import.meta.url));
export const FAMILY_DIR = join(APPS, 'cells');
export const CATALOG_FILE = join(APPS, 'cells.json');

/** 3: every cell names its family. */
export const CATALOG_VERSION = 3;

const NOTE =
  'GENERATED by scripts/truth/catalog.ts from fixtures/apps/cells/<family>.json — edit those, then rerun it. The lab apps\' cell catalog (docs/plans/2026-10-15-ground-truth-lab-app.md). Both apps bundle this file and route a cell by its `family`. A target is a solid rectangle of its own colour with no visible text, identified as lab.<cell>.<tag>; `declared` is what the cell builds, the truth\'s first source (scripts/truth/schema.ts). A form cell (`form`) has no coloured targets: its fields, submit and picker rows are identified as lab.<cell>.<tag> (a picker row lab.<cell>.<field>.<code>), and its truth is the app\'s own model of each field (value, focus, the error it shows), the keyboard\'s frame and every submit (scripts/truth/schema.ts#FormState).';

/** One family's file: its cells without `family` (the file says it). */
export interface FamilyFile {
  family: Family;
  /** What the family builds, and which notes its cells calibrate. */
  note: string;
  cells: CatalogCell[];
}

/** The catalog the family files make: the families in FAMILIES's order, ids unique across them. */
export function buildCatalog(files: readonly FamilyFile[]): Catalog {
  const byFamily = new Map(files.map((f) => [f.family, f]));
  const unknown = files.filter((f) => !(FAMILIES as readonly string[]).includes(f.family)).map((f) => f.family);
  if (unknown.length > 0) throw new Error(`catalog: no family ${unknown.join(', ')} (schema.ts#FAMILIES)`);
  const missing = FAMILIES.filter((f) => !byFamily.has(f));
  if (missing.length > 0) throw new Error(`catalog: no file for family ${missing.join(', ')}`);
  const cells: CatalogCell[] = [];
  const seen = new Map<string, Family>();
  for (const family of FAMILIES) {
    for (const c of byFamily.get(family)!.cells) {
      if (c.family !== undefined) throw new Error(`catalog: cell ${c.id} in ${family}.json names a family — the file says it`);
      const other = seen.get(c.id);
      if (other !== undefined) throw new Error(`catalog: cell ${c.id} is in ${other}.json and ${family}.json`);
      seen.set(c.id, family);
      // `family` after `id`, so it reads first in the generated file.
      const { id, ...rest } = c;
      cells.push({ id, family, ...rest });
    }
  }
  return { version: CATALOG_VERSION, note: NOTE, cells };
}

/**
 * JSON as the catalog files are written: an object with no array in it, and an array of plain values, on one line
 * (`{ "tag": "A", "color": "#E53935", … }`); everything else one member per line, two spaces deep.
 */
export function formatJson(value: unknown, indent = ''): string {
  const flat = (v: unknown): boolean =>
    v === null || typeof v !== 'object' ? true : Array.isArray(v) ? false : Object.values(v as object).every(flat);
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (value.every((v) => v === null || typeof v !== 'object')) return `[${value.map((v) => JSON.stringify(v)).join(', ')}]`;
    return `[\n${value.map((v) => `${inner}${formatJson(v, inner)}`).join(',\n')}\n${indent}]`;
  }
  const entries = Object.entries(value as object).filter(([, v]) => v !== undefined);
  if (entries.length === 0) return '{}';
  if (flat(value)) return `{ ${entries.map(([k, v]) => `${JSON.stringify(k)}: ${formatJson(v)}`).join(', ')} }`;
  return `{\n${entries.map(([k, v]) => `${inner}${JSON.stringify(k)}: ${formatJson(v, inner)}`).join(',\n')}\n${indent}}`;
}

export async function readFamilies(dir = FAMILY_DIR): Promise<FamilyFile[]> {
  const names = (await readdir(dir)).filter((n) => n.endsWith('.json')).sort();
  return Promise.all(
    names.map(async (n) => {
      const f = JSON.parse(await readFile(join(dir, n), 'utf8')) as FamilyFile;
      if (`${f.family}.json` !== n) throw new Error(`catalog: ${n} says it is family ${f.family}`);
      return f;
    }),
  );
}

/** The text of fixtures/apps/cells.json as the family files make it. */
export async function generatedCatalog(dir = FAMILY_DIR): Promise<string> {
  return `${formatJson(buildCatalog(await readFamilies(dir)))}\n`;
}

/** The bundled catalog, parsed. */
export async function loadCatalog(file = CATALOG_FILE): Promise<Catalog> {
  return JSON.parse(await readFile(file, 'utf8')) as Catalog;
}

/**
 * The cells a capture asks for: those of the named families, then (both given: of those) the named cells, in catalog
 * order; all of them when neither is given. Strict, as golden's --only: a family or cell that names nothing is an error.
 */
export function selectCells(catalog: Catalog, opts: { families?: readonly string[]; cells?: readonly string[] }): CatalogCell[] {
  const badFamily = (opts.families ?? []).filter((f) => !(FAMILIES as readonly string[]).includes(f));
  if (badFamily.length > 0) throw new Error(`no family ${badFamily.join(', ')} (${FAMILIES.join(', ')})`);
  const badCell = (opts.cells ?? []).filter((id) => !catalog.cells.some((c) => c.id === id));
  if (badCell.length > 0) throw new Error(`no cell ${badCell.join(', ')} in the catalog`);
  const picked = catalog.cells.filter(
    (c) => (opts.families === undefined || opts.families.includes(c.family ?? '')) && (opts.cells === undefined || opts.cells.includes(c.id)),
  );
  if (picked.length === 0) throw new Error(`no cell selected: families ${opts.families?.join(', ') ?? 'any'}, cells ${opts.cells?.join(', ') ?? 'any'}`);
  return picked;
}

/** The family of each cell of the catalog — how a capture's KNOWN rows are grouped (tests/differential/golden/). */
export const familyOf = (catalog: Catalog, cell: string): Family | undefined => catalog.cells.find((c) => c.id === cell)?.family;

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
  const text = await generatedCatalog();
  if (values.check === true) {
    const now = await readFile(CATALOG_FILE, 'utf8');
    if (now !== text) {
      console.error('fixtures/apps/cells.json is stale: run node --import tsx scripts/truth/catalog.ts');
      process.exitCode = 1;
    }
  } else {
    await writeFile(CATALOG_FILE, text);
  }
}
